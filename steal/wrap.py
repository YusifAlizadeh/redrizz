#!/usr/bin/env python3
"""
Turn a STOLEN attack (captured by steal/sniffer.py) into a farmable exploit, so
the farm fires it back at every team automatically every tick.

    python steal/wrap.py <service>     # wraps the newest capture for that service

It writes exploits/stolen_<service>.py. That file just calls replay.py with the
newest capture against the single host the farm passes it -- which means it obeys
the farm's "print flags to stdout" contract. Delete the file to stop farming it.
"""
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config  # noqa: E402

WRAPPER = '''#!/usr/bin/env python3
# AUTO-GENERATED by steal/wrap.py -- replays the newest stolen "{svc}" attack
# against the one host the farm passes in. Delete this file to stop farming it.
import os, sys
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
host = sys.argv[1] if len(sys.argv) > 1 else "127.0.0.1"
os.execvp(sys.executable, [sys.executable, os.path.join(HERE, "steal", "replay.py"),
                           "--latest", "{svc}", "--target", host])
'''


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: python steal/wrap.py <service>")
    svc = sys.argv[1]
    cap_dir = os.path.join(config.CAPTURE_DIR, svc)
    if not os.path.isdir(cap_dir) or not os.listdir(cap_dir):
        sys.exit(f"no captures for '{svc}' in {cap_dir} -- run the sniffer first")
    out = os.path.join(config.BASE_DIR, "exploits", f"stolen_{svc}.py")
    with open(out, "w") as f:
        f.write(WRAPPER.format(svc=svc))
    os.chmod(out, 0o755)
    print(f"[+] wrote {out}")
    print(f"    the farm will now replay the newest stolen '{svc}' attack to all teams.")
    print(f"    test it:  python {out} <some-host>")


if __name__ == "__main__":
    main()
